"""Generate python/neper/_orilib_doc.py, the documentation of the Orilib
functions (C prototypes and descriptions), from dev/orilib/*.rst, for
the docstrings of neper.orilib (the inputs and outputs of the functions are
given by the orilib program, orilib signatures).

Run from the top-level directory: python3 python/tools/orilib_doc.py
(test_orilib.py checks that the file is up to date)."""

import pprint
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "dev" / "orilib"
OUT = ROOT / "python" / "neper" / "_orilib_doc.py"


def _clean(text):
    text = re.sub(r":math:`([^`]*)`", r"\1", text)
    text = re.sub(r":[a-z:]+:`([^`<]*)(?: <[^>]*>)?`", r"\1", text)
    text = text.replace("``", "").replace("\\", "")
    text = re.sub(r"\[#\w*\]_", "", text)
    text = re.sub(r"(?<!\w)\*(\w+)\*", r"\1", text)
    return re.sub(r"[ \t]+", " ", text).strip()


def docs():
    """Prototype and description of the Orilib functions (developer
    documentation)."""
    out = {}
    for rst in sorted(DOC.glob("*.rst")):
        lines = rst.read_text().splitlines()
        i = 0
        while i < len(lines):
            if not lines[i].startswith(".. c:function::"):
                i += 1
                continue
            protos = [lines[i][len(".. c:function::"):].strip()]
            i += 1
            while i < len(lines) and lines[i].strip() and lines[i].startswith(" " * 16):
                protos.append(lines[i].strip())
                i += 1
            desc = []
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith("   ")):
                if lines[i].strip().startswith(".. "):
                    break
                desc.append(lines[i].strip())
                i += 1
            paragraphs = [_clean(p) for p in "\n".join(desc).split("\n\n") if p.strip()]
            text = "\n\n".join(paragraphs)
            for proto in protos:
                m = re.search(r"\b(ol_\w+) \(", proto)
                if m:
                    out[m.group(1)] = {"proto": re.sub(r"\s+", " ", proto), "doc": text}
    return out


def text():
    return ("# Generated by python/tools/orilib_doc.py from dev/orilib/*.rst: do not edit.\n\n"
            "DOCS = " + pprint.pformat(docs(), width=100, sort_dicts=True) + "\n")


if __name__ == "__main__":
    OUT.write_text(text())
    print(f"{OUT}: {len(docs())} functions", file=sys.stderr)
